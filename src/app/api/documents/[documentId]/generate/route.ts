// src/app/api/documents/[documentId]/generate/route.ts
import { NextRequest, NextResponse } from 'next/server';
import { requireAuth } from '@/lib/auth';
import { prisma } from '@/lib/prisma';
import { 
  callAIToGenerateNote, 
  callAIToGenerateQuiz, 
  callAIToGenerateFlashcards 
} from '@/lib/aiGeneration'; // <--- CHANGED: Use the robust Gemini/Groq library

// Maximize execution time for Hobby Plan (60s)
export const maxDuration = 60; 

export async function POST(
  req: NextRequest,
  { params }: { params: { documentId: string } }
) {
  try {
    const user = await requireAuth(req);
    const { documentId } = params;
    
    // Get the specific task from query params (e.g., ?type=quiz)
    const { searchParams } = new URL(req.url);
    const type = searchParams.get('type'); // 'notes', 'quiz', 'flashcards'

    if (!['notes', 'quiz', 'flashcards'].includes(type || '')) {
      return NextResponse.json({ error: "Invalid or missing 'type' parameter" }, { status: 400 });
    }

    // 1. Fetch Document Text
    const doc = await prisma.documents.findUnique({
      where: { id: documentId, user_id: user.id },
      select: { id: true, extracted_text: true, file_name: true }
    });

    if (!doc || !doc.extracted_text) {
      return NextResponse.json({ error: "Document text not found" }, { status: 404 });
    }

    const textContext = doc.extracted_text;
    const baseTitle = doc.file_name.replace(/\.[^/.]+$/, "");

    // 2. Switch on Task Type
    let result;
    
    if (type === 'notes') {
      // Returns { title, content } (HTML string)
      const noteData = await callAIToGenerateNote(textContext);
      
      result = await prisma.notes.create({
        data: {
          user_id: user.id,
          document_id: doc.id,
          title: noteData.title || `${baseTitle} - Notes`,
          content: noteData.content,
          tags: ['ai-generated']
        }
      });
    } 
    
    else if (type === 'quiz') {
      // Returns { title, questions: [] }
      const quizData = await callAIToGenerateQuiz(textContext, 10, 'medium');
      
      result = await prisma.quiz.create({
        data: {
          userId: user.id,
          document_id: doc.id,
          title: quizData.title || `${baseTitle} - Quiz`,
          questions: {
            create: quizData.questions.map((q: any) => ({
              question_text: q.question_text,
              question_type: q.question_type,
              correct_answer: q.correct_answer,
              options: q.options || [],
              explanation: q.explanation || "Generated by AI"
            }))
          }
        }
      });
    } 
    
    else if (type === 'flashcards') {
      // Returns array of objects { front_content, back_content }
      const cardsData = await callAIToGenerateFlashcards(textContext, 15);
      
      result = await prisma.flashcard_decks.create({
        data: {
          user_id: user.id,
          document_id: doc.id,
          title: `${baseTitle} - Flashcards`,
          flashcards: {
            create: cardsData.map((c: any) => ({
              front_content: c.front_content, // Note key change if mapping from different lib
              back_content: c.back_content
            }))
          }
        }
      });
    }

    return NextResponse.json({ success: true, type, data: result });

  } catch (error: any) {
    console.error(`Generation Error (${params.documentId}):`, error);
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}